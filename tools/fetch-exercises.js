#!/usr/bin/env node
/* fetch-exercises.js - pull the exercises the program uses from free-exercise-db
   (public domain, https://github.com/yuhonas/free-exercise-db) and write:
     img/ex/<id>/0.jpg, img/ex/<id>/1.jpg     the two photo frames
     exercises.js                             window.EXDB = { id: {...} }  (loaded by index.html)

   Usage:  node tools/fetch-exercises.js
   Re-run any time the id list in program-ids.js changes. Exits non-zero if an
   id does not exist upstream or an image fails to download. */
'use strict';
const fs = require('fs');
const path = require('path');
const https = require('https');

const RAW = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/';
const root = path.join(__dirname, '..');
const IDS = require('./program-ids.js');

function get(url) {
  return new Promise((res, rej) => {
    https.get(url, r => {
      if (r.statusCode === 301 || r.statusCode === 302) return get(r.headers.location).then(res, rej);
      if (r.statusCode !== 200) return rej(new Error(r.statusCode + ' ' + url));
      const chunks = [];
      r.on('data', c => chunks.push(c));
      r.on('end', () => res(Buffer.concat(chunks)));
    }).on('error', rej);
  });
}

(async () => {
  const all = JSON.parse((await get(RAW + 'dist/exercises.json')).toString('utf8'));
  const byId = {};
  all.forEach(e => { byId[e.id] = e; });
  const missing = IDS.filter(id => !byId[id]);
  if (missing.length) { console.error('Unknown ids: ' + missing.join(', ')); process.exit(1); }

  const out = {};
  for (const id of IDS) {
    const e = byId[id];
    const dir = path.join(root, 'img', 'ex', id);
    fs.mkdirSync(dir, { recursive: true });
    const imgs = [];
    for (let i = 0; i < Math.min(2, e.images.length); i++) {
      const dest = path.join(dir, i + '.jpg');
      if (!fs.existsSync(dest)) fs.writeFileSync(dest, await get(RAW + 'exercises/' + e.images[i]));
      imgs.push('img/ex/' + id + '/' + i + '.jpg');
    }
    if (imgs.length < 2) { console.error(id + ' has ' + imgs.length + ' image(s)'); process.exit(1); }
    out[id] = {
      name: e.name, equipment: e.equipment, level: e.level, mechanic: e.mechanic,
      primary: e.primaryMuscles, secondary: e.secondaryMuscles,
      instructions: e.instructions, images: imgs
    };
    process.stdout.write('.');
  }
  fs.writeFileSync(path.join(root, 'exercises.js'),
    '/* generated by tools/fetch-exercises.js from free-exercise-db (public domain) */\n' +
    'window.EXDB=' + JSON.stringify(out) + ';\n');
  console.log('\n' + IDS.length + ' exercises, images in img/ex/, data in exercises.js');
})().catch(e => { console.error(e.message); process.exit(1); });
